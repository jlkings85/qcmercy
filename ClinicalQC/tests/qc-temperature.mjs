const greene={id:'4247bc0a-7403-4c3e-ae6b-1909ad27796b'},ordinary={id:'other',label:'3200'},special={id:'6cc6f543-d536-41bd-88ce-34cae2b38528',label:'3101'},settings={qcEnabled:true,revision:1};
